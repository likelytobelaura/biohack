"""Generates mk.inc: the two vector GEMM micro-kernels of mnist.c (an 8x16 output tile each).

    python3 gen_mk.py > mk.inc

Registers: f0..f15 the tile (row i in f(2i), f(2i+1)), f16/f17 and f26/f27 the two B rows in flight,
f18..f25 the eight broadcast A values. B rows are read with flwg.ps (this shire's L2, no L1), A values
with fbc.ps through the L1 (the caller evicts the A buffer from its L1 first), the tile is written with
fswg.ps. Erratum 1.29: every loaded register is forced with fmv.x.w x0 before its first use, B one half
ahead, and eight nops separate the last fmadd from the stores. The B row after the last one is read (and
ignored), so every B buffer has a readable row after it.

mk_f: out[i][0:16] = sum_k A[row i][k] * B[k][0:16]   A(i,k) = p_i + 4k       (8 row pointers)
mk_g: out[i][0:16] = sum_k A[k][i] * B[k][0:16]       A(i,k) = pa + 4i + k*ak (k even from pa0, odd from pa1)
K must be even; the asm loop runs K/2 times.
"""


def half(wcur, wnext, a_ops):
    lines = [
        f"flw.ps f{wnext[0]}, 0(%[pb])",
        f"flw.ps f{wnext[1]}, 32(%[pb])",
        "add %[pb], %[pb], %[ldb]",
    ]
    lines += [f"fbc.ps f{18 + i}, {a_ops[i]}" for i in range(8)]
    lines += [f"fmv.x.w x0, f{r}" for r in (*wcur, *range(18, 26))]
    for i in range(8):
        lines.append(f"fmadd.ps f{2 * i}, f{18 + i}, f{wcur[0]}, f{2 * i}")
        lines.append(f"fmadd.ps f{2 * i + 1}, f{18 + i}, f{wcur[1]}, f{2 * i + 1}")
    return lines


def body(kind):
    st = "fswg.ps"
    if kind == "f":
        a0 = [f"0(%[p{i}])" for i in range(8)]
        a1 = [f"4(%[p{i}])" for i in range(8)]
        step = [f"addi %[p{i}], %[p{i}], 8" for i in range(8)]
    else:
        a0 = [f"{4 * i}(%[pa0])" for i in range(8)]
        a1 = [f"{4 * i}(%[pa1])" for i in range(8)]
        step = ["add %[pa0], %[pa0], %[ak2]", "add %[pa1], %[pa1], %[ak2]"]
    pre = [f"fbcx.ps f{r}, zero" for r in range(16)]
    pre += ["flw.ps f16, 0(%[pb])", "flw.ps f17, 32(%[pb])", "add %[pb], %[pb], %[ldb]"]
    loop = ["1:"] + half((16, 17), (26, 27), a0) + half((26, 27), (16, 17), a1) + step
    loop += ["addi %[n], %[n], -1", "bnez %[n], 1b"]
    post = ["nop"] * 8
    for i in range(8):
        post += [f"{st} f{2 * i}, (%[po])", "addi %[t0], %[po], 32", f"{st} f{2 * i + 1}, (%[t0])",
                 "add %[po], %[po], %[ldo]"]
    return pre + loop + post


def emit(kind):
    text = "\n".join(f'        "{l}\\n"' for l in body(kind))
    if kind == "f":
        sig = ("INLINE void mk_f(uint64_t p0, uint64_t p1, uint64_t p2, uint64_t p3, uint64_t p4, uint64_t p5,\n"
               "                 uint64_t p6, uint64_t p7, uint64_t pb, uint64_t ldb, uint64_t k, uint64_t po, uint64_t ldo)")
        outs = ("[p0] \"+r\"(p0), [p1] \"+r\"(p1), [p2] \"+r\"(p2), [p3] \"+r\"(p3), [p4] \"+r\"(p4), [p5] \"+r\"(p5),\n"
                "          [p6] \"+r\"(p6), [p7] \"+r\"(p7), [pb] \"+r\"(pb), [n] \"+r\"(n), [po] \"+r\"(po), [t0] \"=&r\"(t0)")
        ins = "[ldb] \"r\"(ldb), [ldo] \"r\"(ldo)"
        setup = ""
    else:
        sig = ("INLINE void mk_g(uint64_t pa, uint64_t ak, uint64_t pb, uint64_t ldb, uint64_t k, uint64_t po,\n"
               "                 uint64_t ldo)")
        outs = ("[pa0] \"+r\"(pa0), [pa1] \"+r\"(pa1), [pb] \"+r\"(pb), [n] \"+r\"(n), [po] \"+r\"(po),\n"
                "          [t0] \"=&r\"(t0)")
        ins = "[ak2] \"r\"(ak2), [ldb] \"r\"(ldb), [ldo] \"r\"(ldo)"
        setup = "    uint64_t pa0 = pa, pa1 = pa + ak, ak2 = 2 * ak;\n"
    return (f"{sig}\n{{\n{setup}    uint64_t n = k / 2, t0;\n    __asm__ __volatile__(\n{text}\n"
            f"        : {outs}\n        : {ins}\n        : \"memory\", FREGS);\n}}\n")


print("/* Generated by gen_mk.py: do not edit. */\n")
print(emit("f"))
print(emit("g"))


def emit_sum():
    """sum_line: dst line = sum over nsh shires of the line at src + p*stride (nsh a multiple of 8 or under 8).
    Eight shires per round into f16..f31, eight accumulator pairs f0..f15 (one per round slot, so a pair is
    written once per round, 32 instructions apart), then a forced tree."""
    rnd = []
    for s in range(8):
        rnd += [f"flw.ps f{16 + 2 * s}, 0(%[a])", f"flw.ps f{17 + 2 * s}, 32(%[a])", "add %[a], %[a], %[st]"]
    rnd += [f"fmv.x.w x0, f{r}" for r in range(16, 32)]
    rnd += [f"fadd.ps f{r}, f{r}, f{16 + r}" for r in range(16)]
    tree = []
    for lvl in (1, 2, 4):  # pair index step
        srcs = [r for k in range(0, 8, 2 * lvl) for r in (2 * (k + lvl), 2 * (k + lvl) + 1, 2 * k, 2 * k + 1)]
        tree += [f"fmv.x.w x0, f{r}" for r in srcs]
        for k in range(0, 8, 2 * lvl):
            tree += [f"fadd.ps f{2 * k}, f{2 * k}, f{2 * (k + lvl)}",
                     f"fadd.ps f{2 * k + 1}, f{2 * k + 1}, f{2 * (k + lvl) + 1}"]
    one = ["flw.ps f16, 0(%[a])", "flw.ps f17, 32(%[a])", "add %[a], %[a], %[st]",
           "fmv.x.w x0, f16", "fmv.x.w x0, f17", "nop", "fadd.ps f0, f0, f16", "fadd.ps f1, f1, f17",
           "fmv.x.w x0, f0", "fmv.x.w x0, f1", "nop"]
    lines = [f"fbcx.ps f{r}, zero" for r in range(16)]
    lines += ["beqz %[r8], 3f", "2:"] + rnd + ["addi %[r8], %[r8], -1", "bnez %[r8], 2b", "3:"]
    lines += ["nop"] * 8 + tree
    lines += ["beqz %[r1], 5f", "4:"] + one + ["addi %[r1], %[r1], -1", "bnez %[r1], 4b", "5:"]
    lines += ["nop"] * 8 + ["fswg.ps f0, (%[d])", "addi %[t0], %[d], 32", "fswg.ps f1, (%[t0])"]
    text = "\n".join(f'        "{l}\\n"' for l in lines)
    return ("INLINE void sum_line(uint64_t d, uint64_t a, uint64_t st, uint64_t nsh)\n{\n"
            "    uint64_t r8 = nsh / 8, r1 = nsh % 8, t0;\n    __asm__ __volatile__(\n" + text +
            "\n        : [a] \"+r\"(a), [r8] \"+r\"(r8), [r1] \"+r\"(r1), [t0] \"=&r\"(t0)\n"
            "        : [d] \"r\"(d), [st] \"r\"(st)\n        : \"memory\", FREGS);\n}\n")


print(emit_sum())
